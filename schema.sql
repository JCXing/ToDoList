-- ============================================================
-- 知栖 · 个人信息管家 —— Supabase 数据库结构
--
-- 使用方法：打开 https://supabase.com → 你的项目 →
--   左侧 SQL Editor → New query → 把本文件全部内容粘贴进去 → Run
--
-- 重复执行是安全的：所有语句都带「不存在才创建」。
-- 数据隔离：每张表都开行级安全（RLS），每个登录用户只能
-- 读写 owner_id 等于自己账号 id 的行，互相完全不可见。
-- ============================================================

-- -----------------------------------------------------------
-- 1. 记录表（想法 / 资料 / 待办 / 笔记）
-- -----------------------------------------------------------
create table if not exists public.entries (
  id          bigint generated by default as identity primary key,
  owner_id    uuid        not null default auth.uid(),
  owner_name  text,
  kind        text        not null default 'note',      -- idea | material | todo | note
  title       text        not null default '',
  content     text        not null default '',
  category    text,
  tags        jsonb       not null default '[]',
  summary     text,
  key_points  jsonb       not null default '[]',
  priority    text,
  due_date    date,
  related_ids jsonb       not null default '[]',
  idea_status text,                                      -- 想法状态：孵化中 / 已立项 / 已落地 / 已放弃
  task_ids    jsonb       not null default '[]',         -- 由这条记录派生的任务 id
  done        boolean     not null default false,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);

-- -----------------------------------------------------------
-- 2. 任务表（任务台）
-- -----------------------------------------------------------
create table if not exists public.tasks (
  id           bigint generated by default as identity primary key,
  owner_id     uuid        not null default auth.uid(),
  owner_name   text,
  name         text        not null default '',
  status       text        not null default '待办',     -- 待办 | 进行中 | 已延期 | 已完成
  priority     text        not null default 'P2 中',
  category     text        not null default '其他',
  due_date     date,
  delay_reason text        not null default '',
  tags         text        not null default '',
  done_at      text        not null default '',
  detail       text        not null default '',
  images       jsonb       not null default '[]',
  next_action  text        not null default '',
  source_idea  text,
  delay_count  int         not null default 0,
  delay_log    text        not null default '',
  first_due    date,
  created_at   timestamptz not null default now(),
  updated_at   timestamptz not null default now()
);

-- -----------------------------------------------------------
-- 3. 阶段总结表
-- -----------------------------------------------------------
create table if not exists public.summaries (
  id          bigint generated by default as identity primary key,
  owner_id    uuid        not null default auth.uid(),
  owner_name  text,
  title       text,
  period_start date,
  period_end   date,
  content     text,
  actions     jsonb       not null default '[]',
  entry_count int,
  created_at  timestamptz not null default now()
);

-- -----------------------------------------------------------
-- 4. 问答记录表
-- -----------------------------------------------------------
create table if not exists public.qa_logs (
  id         bigint generated by default as identity primary key,
  owner_id   uuid        not null default auth.uid(),
  owner_name text,
  question   text,
  answer     text,
  cited_ids  jsonb       not null default '[]',
  created_at timestamptz not null default now()
);

-- -----------------------------------------------------------
-- 行级安全：四张表全部「只许动自己的行」
-- -----------------------------------------------------------
alter table public.entries   enable row level security;
alter table public.tasks     enable row level security;
alter table public.summaries enable row level security;
alter table public.qa_logs   enable row level security;

-- entries
drop policy if exists "own_entries_select" on public.entries;
drop policy if exists "own_entries_insert" on public.entries;
drop policy if exists "own_entries_update" on public.entries;
drop policy if exists "own_entries_delete" on public.entries;
create policy "own_entries_select" on public.entries for select
  using (auth.uid() = owner_id);
create policy "own_entries_insert" on public.entries for insert
  with check (auth.uid() = owner_id);
create policy "own_entries_update" on public.entries for update
  using (auth.uid() = owner_id) with check (auth.uid() = owner_id);
create policy "own_entries_delete" on public.entries for delete
  using (auth.uid() = owner_id);

-- tasks
